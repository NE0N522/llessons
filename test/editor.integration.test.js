const { test } = require('node:test');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const { createApp } = require('../server/app');
const { hashPassword } = require('../server/auth');

const teacherLogin = 'editor.teacher';
const teacherPassword = 'EditorTeacher#2026';
const studentLogin = 'editor.student';
const studentPassword = 'EditorStudent#2026';

async function signIn(page, base, login, password) {
  await page.goto(`${base}/login.html`);
  await page.locator('[name="login"]').fill(login);
  await page.locator('[name="password"]').fill(password);
  await page.locator('[data-login-form] button[type="submit"]').click();
  await page.waitForURL((url) => !url.pathname.endsWith('/login.html'), { timeout: 10000 });
}

test('Stage 3: CodeMirror works offline with Emmet, no-hints mode, saved preferences and review line numbers', { timeout: 90000 }, async () => {
  const app = await createApp({ pgliteDir: ':memory:', sessionSecret: 'stage3-editor-test-session-secret-at-least-32' });
  const server = app.listen(0, '127.0.0.1');
  await new Promise((resolve) => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  let browser;
  const errors = [];
  try {
    const db = app.locals.db;
    const stamp = new Date().toISOString();
    const teacherHash = await hashPassword(teacherPassword);
    const studentHash = await hashPassword(studentPassword);
    const teacherId = (await db.query("INSERT INTO users(role,login,password_hash,full_name,is_owner,created_at) VALUES('teacher',$1,$2,'Редактор тест',1,$3) RETURNING id", [teacherLogin, teacherHash, stamp])).rows[0].id;
    const classId = (await db.query('INSERT INTO classes(teacher_id,name,created_at) VALUES($1,$2,$3) RETURNING id', [teacherId, 'Класс редактора', stamp])).rows[0].id;
    const studentId = (await db.query("INSERT INTO users(role,login,password_hash,full_name,class_id,must_change_password,created_at) VALUES('student',$1,$2,'Ученик редактора',$3,0,$4) RETURNING id", [studentLogin, studentHash, classId, stamp])).rows[0].id;
    const hintedId = (await db.query(`INSERT INTO assignments(class_id,title,description,starter_html,starter_css,allow_resubmit,no_hints,status,checks_json,created_at,updated_at)
      VALUES($1,'Работа с подсказками','Проверь редактор.','<main><h1>Начало</h1></main>','main { color: navy; }',1,0,'published','[]',$2,$2) RETURNING id`, [classId, stamp])).rows[0].id;
    const noHintsId = (await db.query(`INSERT INTO assignments(class_id,title,description,starter_html,starter_css,allow_resubmit,no_hints,status,checks_json,created_at,updated_at)
      VALUES($1,'Работа без подсказок','Подсказки отключены.','<main><h1>Стартовый текст</h1></main>','main { color: navy; }',1,1,'published','[]',$2,$2) RETURNING id`, [classId, stamp])).rows[0].id;
    const submissionId = (await db.query(`INSERT INTO submissions(assignment_id,student_id,status,submitted_at,created_at,updated_at)
      VALUES($1,$2,'submitted',$3,$3,$3) RETURNING id`, [hintedId, studentId, stamp])).rows[0].id;
    await db.query("INSERT INTO submission_versions(submission_id,html,css,kind,created_at) VALUES($1,'<main>\\n  <h1>Работа ученика</h1>\\n</main>','main { color: navy; }','submitted',$2)", [submissionId, stamp]);

    browser = await chromium.launch({ headless: true });
    const course = await browser.newPage({ viewport: { width: 1280, height: 900 }, colorScheme: 'light' });
    course.on('pageerror', (error) => errors.push(`course pageerror: ${error.message}`));
    course.on('console', (message) => { if (message.type() === 'error') errors.push(`course console: ${message.text()}`); });
    course.on('request', (request) => { if (new URL(request.url()).origin !== base) errors.push(`external request: ${request.url()}`); });
    await course.goto(`${base}/lesson-view.html?lesson=1`, { waitUntil: 'domcontentloaded' });
    const playground = course.locator('[data-playground]').first();
    await playground.waitFor();
    await playground.scrollIntoViewIfNeeded();
    const editor = playground.locator('.cm-editor').first();
    await editor.waitFor({ timeout: 15000 });
    assert.equal(await playground.locator('textarea').count(), 0, 'course playground must not use a textarea');
    const htmlContent = playground.locator('[data-editor-host="html"] .cm-content');
    await htmlContent.click();
    await course.keyboard.press('Control+A');
    await course.keyboard.type('div.card>h2+p');
    await course.keyboard.press('Tab');
    await course.waitForFunction(() => document.querySelector('.playground .cm-content')?.textContent.includes('class="card"'), null, { timeout: 10000 });
    const expanded = await htmlContent.textContent();
    assert.match(expanded, /<div class="card">[\s\S]*<h2><\/h2>[\s\S]*<p><\/p>/);
    assert.equal(await playground.locator('.cm-gutterElement').count() > 0, true, 'editor should show separate line numbers');
    const expandHtml = async (abbreviation) => {
      await htmlContent.click();
      await course.keyboard.press('Control+A');
      await course.keyboard.type(abbreviation);
      await course.keyboard.press('Tab');
      return htmlContent.textContent();
    };
    assert.match(await expandHtml('!'), /<!doctype html>/i, 'the ! abbreviation should expand to an HTML5 document');
    assert.equal((await expandHtml('ul>li*3')).match(/<li>/g)?.length, 3, 'Emmet should expand repeated list items');
    assert.match(await expandHtml('img'), /<img\b/i);
    assert.match(await expandHtml('a'), /<a\b[^>]*href=/i);
    assert.match(await expandHtml('table'), /<table\b/i);
    await htmlContent.click();
    await course.keyboard.press('Control+A');
    await course.keyboard.type('<div>');
    assert.match(await htmlContent.textContent(), /<div><\/div>/, 'typing > after an opening HTML tag should add its closing tag');
    await course.keyboard.press('Enter');
    assert.equal(await playground.locator('[data-editor-host="html"] .cm-line').count(), 3, 'Enter between paired tags should create an indented inner line');
    await htmlContent.click();
    await course.keyboard.press('Control+A');
    await course.keyboard.type('<p>Комментарий</p>');
    await course.keyboard.press('Control+/');
    assert.match(await htmlContent.textContent(), /<!--/);
    await playground.locator('[data-font-plus]').click();
    await course.waitForFunction(() => document.querySelector('.playground [data-font-label]')?.textContent === '16 px');
    await course.locator('[data-theme-toggle]').click();
    await course.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
    await course.waitForFunction(() => getComputedStyle(document.querySelector('.playground .cm-editor')).backgroundColor === 'rgb(27, 38, 56)');
    assert.equal(await editor.evaluate((node) => getComputedStyle(node).backgroundColor), 'rgb(27, 38, 56)');
    await htmlContent.click();
    await course.keyboard.press('Control+A');
    await course.keyboard.type('<div><p></div>');
    await playground.locator('.cm-lintRange-error').first().waitFor({ timeout: 10000 });

    await course.goto(`${base}/lesson-view.html?lesson=5`, { waitUntil: 'domcontentloaded' });
    const cssPlayground = course.locator('[data-playground]').first();
    await cssPlayground.scrollIntoViewIfNeeded();
    await cssPlayground.locator('[data-editor-host="css"] .cm-editor').waitFor({ state: 'attached', timeout: 15000 });
    await cssPlayground.locator('[data-tab="css"]').click();
    const cssContent = cssPlayground.locator('[data-editor-host="css"] .cm-content');
    await cssContent.click();
    await course.keyboard.press('Control+A');
    await course.keyboard.type('df');
    assert.match(await cssContent.textContent(), /df/, 'typing into the CSS editor should update its document');
    await course.keyboard.press('Tab');
    assert.match(await cssContent.textContent(), /display:\s*flex/);
    await cssContent.click();
    await course.keyboard.press('Control+A');
    await course.keyboard.type('m10');
    await course.keyboard.press('Tab');
    assert.match(await cssContent.textContent(), /margin:\s*10px/);
    await cssContent.click();
    await course.keyboard.press('Control+A');
    await course.keyboard.type('body { colr: red; }');
    await cssPlayground.locator('.cm-lintRange-warning').first().waitFor({ timeout: 10000 });
    await cssContent.click();
    await course.keyboard.press('Control+A');
    await course.keyboard.type('col');
    await cssPlayground.locator('.cm-tooltip').waitFor({ timeout: 10000 });
    assert.match(await cssPlayground.locator('.cm-tooltip').textContent(), /color/, 'typing a CSS property prefix should offer matching properties');
    await cssContent.click();
    await course.keyboard.press('Control+A');
    await course.keyboard.type('body { color: red; }');
    await course.keyboard.press('Control+/');
    assert.match(await cssContent.textContent(), /\/\*[\s\S]*\*\//, 'Ctrl+/ should comment CSS code');
    await cssContent.click();
    await course.keyboard.press('Control+A');
    await course.keyboard.type('body { color: red; }');
    await course.keyboard.press('Control+/');
    assert.match(await cssContent.textContent(), /body\s*\{\s*color:\s*red;\s*\}/, 'Ctrl+/ should also uncomment CSS code');
    await cssContent.click();
    await course.keyboard.press('Control+A');
    await course.keyboard.type('body {\n  color: red;\n}');
    await course.keyboard.press('Control+A');
    await course.keyboard.press('Shift+Tab');
    assert.doesNotMatch(await cssContent.textContent(), /\n {2}color:/, 'Shift+Tab should decrease indentation for selected lines');

    const student = await browser.newPage({ viewport: { width: 375, height: 812 }, colorScheme: 'light' });
    student.on('pageerror', (error) => errors.push(`student pageerror: ${error.message}`));
    student.on('console', (message) => { if (message.type() === 'error') errors.push(`student console: ${message.text()}`); });
    student.on('request', (request) => { if (new URL(request.url()).origin !== base) errors.push(`external request: ${request.url()}`); });
    await signIn(student, base, studentLogin, studentPassword);
    await student.goto(`${base}/student/assignment.html?id=${noHintsId}`, { waitUntil: 'domcontentloaded' });
    await student.locator('[data-editor-host="html"] .cm-editor').waitFor({ timeout: 15000 });
    assert.match(await student.locator('[data-hints-warning]').textContent(), /отключил подсказки/i);
    const noHintsEditor = student.locator('[data-editor-host="html"] .cm-content');
    await noHintsEditor.click();
    await student.keyboard.press('Control+A');
    await student.keyboard.type('div');
    await student.keyboard.press('Tab');
    const unexpanded = await noHintsEditor.textContent();
    assert.doesNotMatch(unexpanded, /<div/i, 'Tab should indent instead of expanding Emmet when hints are disabled');
    assert.equal(await student.locator('[data-editor-host="html"] .cm-lintRange-error, [data-editor-host="html"] .cm-lintRange-warning').count(), 0, 'soft checks should be off with hints:false');
    await noHintsEditor.click();
    await student.keyboard.press('Control+A');
    await student.keyboard.type('<div>');
    assert.doesNotMatch(await noHintsEditor.textContent(), /<\/div>/, 'auto-closing tags should be disabled when hints are disabled');
    await noHintsEditor.click();
    await student.keyboard.press('Control+A');
    await student.keyboard.type('"');
    assert.equal((await noHintsEditor.textContent()).match(/"/g)?.length, 1, 'bracket and quote pairing should be disabled when hints are disabled');
    await student.locator('[data-font-plus]').click();
    await student.waitForFunction(async () => (await (await fetch('/api/student/settings/editor')).json()).font_size === 16);
    await student.reload({ waitUntil: 'domcontentloaded' });
    await student.locator('[data-editor-host="html"] .cm-editor').waitFor({ timeout: 15000 });
    assert.equal(await student.locator('[data-font-label]').textContent(), '16 px', 'server font preference should be restored on a later page load');

    const formatContent = student.locator('[data-editor-host="html"] .cm-content');
    await formatContent.click();
    await student.keyboard.press('Control+A');
    await student.keyboard.type('<main><h1>Новый заголовок</h1><p>Короткий текст</p></main>');
    await student.locator('[data-format="html"]').click();
    await student.waitForFunction(() => document.querySelectorAll('[data-editor-host="html"] .cm-line').length > 1);
    await formatContent.click();
    await student.keyboard.press('Control+Z');
    await student.waitForFunction(() => document.querySelector('[data-editor-host="html"] .cm-content')?.textContent.includes('Новый заголовок'));
    assert.equal(await student.locator('[data-editor-host="html"] .cm-line').count(), 1, 'Ctrl+Z should restore the unformatted one-line document');
    const formatCss = student.locator('[data-editor-host="css"] .cm-content');
    await formatCss.click();
    await student.keyboard.press('Control+A');
    await student.keyboard.type('main{color:navy;background:white}');
    await student.locator('[data-format="css"]').click();
    await student.waitForFunction(() => document.querySelectorAll('[data-editor-host="css"] .cm-line').length > 1);
    await formatCss.click();
    await student.keyboard.press('Control+Z');
    await student.waitForFunction(() => document.querySelector('[data-editor-host="css"] .cm-content')?.textContent.includes('background:white'));
    assert.equal(await student.locator('[data-editor-host="css"] .cm-line').count(), 1, 'CSS Ctrl+Z should restore its unformatted one-line document');
    await student.locator('[data-save]').click();
    await student.waitForFunction(() => !document.querySelector('[data-save-status]')?.textContent.includes('Сохраняю'));

    await student.locator('[data-reset-starter]').click();
    await student.getByRole('button', { name: 'Сохранить копию и сбросить' }).click();
    await student.waitForFunction(() => document.querySelector('[data-editor-host="html"] .cm-content')?.textContent.includes('Стартовый текст'));
    await student.locator('[data-version-history] summary').click();
    await student.locator('[data-restore-version]').waitFor();
    await student.locator('[data-restore-version]').click();
    await student.getByRole('button', { name: 'Вернуть версию' }).click();
    await student.waitForFunction(() => document.querySelector('[data-editor-host="html"] .cm-content')?.textContent.includes('Новый заголовок'));

    const teacher = await browser.newPage({ viewport: { width: 1280, height: 900 }, colorScheme: 'dark' });
    teacher.on('pageerror', (error) => errors.push(`teacher pageerror: ${error.message}`));
    teacher.on('console', (message) => { if (message.type() === 'error') errors.push(`teacher console: ${message.text()}`); });
    await signIn(teacher, base, teacherLogin, teacherPassword);
    await teacher.goto(`${base}/teacher/index.html`, { waitUntil: 'domcontentloaded' });
    await teacher.locator(`[data-open-class="${classId}"]`).click();
    await teacher.locator('.account-workspace-sidebar [data-tab="submissions"]').click();
    await teacher.locator(`[data-open-submission="${submissionId}"]`).click();
    const reviewHtml = teacher.locator('[data-review-code="html"] .cm-editor');
    await reviewHtml.waitFor({ timeout: 15000 });
    assert.equal(await reviewHtml.locator('.cm-gutterElement').count() > 0, true, 'read-only review editor should retain line numbers');
    assert.equal(await reviewHtml.locator('.cm-content').getAttribute('contenteditable'), 'false', 'review code must be read-only');
    await teacher.locator('[data-review-language="css"]').click();
    assert.equal(await teacher.locator('[data-review-code="html"]').isHidden(), true);
    assert.equal(await teacher.locator('[data-review-code="css"]').isVisible(), true);

    assert.deepEqual(errors, [], 'the editor should load locally without browser errors or external requests');
  } finally {
    await browser?.close();
    await new Promise((resolve) => server.close(resolve));
    await app.locals.db.close();
  }
});
