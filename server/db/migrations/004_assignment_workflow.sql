  ADD COLUMN IF NOT EXISTS model_css text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS model_preview text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS quiz_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS hints_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS checklist_autograde smallint NOT NULL DEFAULT 0 CHECK (checklist_autograde IN (0,1)),
  ADD COLUMN IF NOT EXISTS late_penalty_percent_per_day integer NOT NULL DEFAULT 0 CHECK (late_penalty_percent_per_day BETWEEN 0 AND 100),
  ADD COLUMN IF NOT EXISTS late_penalty_max_percent integer NOT NULL DEFAULT 0 CHECK (late_penalty_max_percent BETWEEN 0 AND 100);

ALTER TABLE classes
  ADD COLUMN IF NOT EXISTS similarity_enabled smallint NOT NULL DEFAULT 0 CHECK (similarity_enabled IN (0,1)),
  ADD COLUMN IF NOT EXISTS similarity_threshold integer NOT NULL DEFAULT 75 CHECK (similarity_threshold BETWEEN 25 AND 100);

ALTER TABLE submissions
  ADD COLUMN IF NOT EXISTS draft_revision integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS auto_score integer,
  ADD COLUMN IF NOT EXISTS late_penalty_percent integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS late_penalty_waived smallint NOT NULL DEFAULT 0 CHECK (late_penalty_waived IN (0,1)),
  ADD COLUMN IF NOT EXISTS client_submitted_at timestamptz,
  ADD COLUMN IF NOT EXISTS auto_checks_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS quiz_answers_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS hint_count integer NOT NULL DEFAULT 0;

ALTER TABLE submission_versions
  DROP CONSTRAINT IF EXISTS submission_versions_kind_check;
ALTER TABLE submission_versions
  ADD CONSTRAINT submission_versions_kind_check CHECK (kind IN ('draft','submitted','backup')),
  ADD COLUMN IF NOT EXISTS auto_checks_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS revision_number integer NOT NULL DEFAULT 1;

CREATE TABLE IF NOT EXISTS assignment_hint_opens (
  assignment_id integer NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
  student_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  hint_index integer NOT NULL CHECK (hint_index BETWEEN 0 AND 2),
  opened_at timestamptz NOT NULL,
  PRIMARY KEY (assignment_id,student_id,hint_index)
);

CREATE TABLE IF NOT EXISTS assignment_due_extensions (
  assignment_id integer NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
  student_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  due_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  PRIMARY KEY (assignment_id,student_id)
);

CREATE TABLE IF NOT EXISTS assignment_line_comments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_id integer NOT NULL REFERENCES submission_versions(id) ON DELETE CASCADE,
  teacher_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  language text NOT NULL CHECK (language IN ('html','css')),
  line_number integer NOT NULL CHECK (line_number BETWEEN 1 AND 10000),
  excerpt text NOT NULL DEFAULT '',
  comment text NOT NULL,
  created_at timestamptz NOT NULL,
  resolved_at timestamptz
);

CREATE TABLE IF NOT EXISTS teacher_comment_templates (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title text NOT NULL,
  body text NOT NULL,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  UNIQUE(teacher_id,title)
);

CREATE TABLE IF NOT EXISTS class_announcements (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id integer NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  teacher_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title text NOT NULL,
  body text NOT NULL,
  pinned smallint NOT NULL DEFAULT 0 CHECK (pinned IN (0,1)),
  created_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS assignment_questions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id integer NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
  student_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  question text NOT NULL,
  teacher_reply text NOT NULL DEFAULT '',
  reply_public smallint NOT NULL DEFAULT 0 CHECK (reply_public IN (0,1)),
  created_at timestamptz NOT NULL,
  replied_at timestamptz,
  student_read_at timestamptz,
  teacher_read_at timestamptz
);

CREATE TABLE IF NOT EXISTS assignment_similarity (
  assignment_id integer NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
  submission_id integer NOT NULL REFERENCES submissions(id) ON DELETE CASCADE,
  other_submission_id integer NOT NULL REFERENCES submissions(id) ON DELETE CASCADE,
  score integer NOT NULL CHECK (score BETWEEN 0 AND 100),
  created_at timestamptz NOT NULL,
  PRIMARY KEY (submission_id,other_submission_id)
);

CREATE INDEX IF NOT EXISTS idx_assignment_hints_student ON assignment_hint_opens(student_id,assignment_id);
CREATE INDEX IF NOT EXISTS idx_assignment_questions_student ON assignment_questions(student_id,assignment_id,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_assignment_line_comments_version ON assignment_line_comments(version_id,line_number);
CREATE INDEX IF NOT EXISTS idx_class_announcements_class ON class_announcements(class_id,created_at DESC);

ALTER TABLE lesson_notes
  ADD COLUMN IF NOT EXISTS revision integer NOT NULL DEFAULT 0;
