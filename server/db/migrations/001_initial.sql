CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role text NOT NULL CHECK (role IN ('teacher', 'student')),
  login text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  full_name text NOT NULL,
  class_id integer,
  active smallint NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  must_change_password smallint NOT NULL DEFAULT 0 CHECK (must_change_password IN (0, 1)),
  is_owner smallint NOT NULL DEFAULT 0 CHECK (is_owner IN (0, 1)),
  created_at timestamptz NOT NULL,
  last_login_at timestamptz
);

CREATE TABLE IF NOT EXISTS classes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name text NOT NULL,
  school_year text NOT NULL DEFAULT '',
  archived smallint NOT NULL DEFAULT 0 CHECK (archived IN (0, 1)),
  created_at timestamptz NOT NULL
);
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_class_id_fkey;
ALTER TABLE users ADD CONSTRAINT users_class_id_fkey FOREIGN KEY (class_id) REFERENCES classes(id) ON DELETE SET NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_single_owner ON users(is_owner) WHERE is_owner=1;

CREATE TABLE IF NOT EXISTS assignments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id integer NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  lesson_id integer,
  starter_html text NOT NULL DEFAULT '',
  starter_css text NOT NULL DEFAULT '',
  due_at timestamptz,
  max_score integer NOT NULL DEFAULT 10 CHECK (max_score BETWEEN 1 AND 100),
  allow_resubmit smallint NOT NULL DEFAULT 1 CHECK (allow_resubmit IN (0, 1)),
  target_all smallint NOT NULL DEFAULT 1 CHECK (target_all IN (0, 1)),
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'archived')),
  checks_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS assignment_targets (
  assignment_id integer NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
  student_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (assignment_id, student_id)
);
CREATE TABLE IF NOT EXISTS submissions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id integer NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
  student_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'submitted', 'returned', 'accepted')),
  score integer CHECK (score IS NULL OR score >= 0),
  teacher_comment text NOT NULL DEFAULT '',
  submitted_at timestamptz,
  graded_at timestamptz,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  UNIQUE (assignment_id, student_id)
);
CREATE TABLE IF NOT EXISTS submission_versions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id integer NOT NULL REFERENCES submissions(id) ON DELETE CASCADE,
  html text NOT NULL DEFAULT '',
  css text NOT NULL DEFAULT '',
  kind text NOT NULL CHECK (kind IN ('draft', 'submitted')),
  created_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS lesson_progress (
  student_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  lesson_id integer NOT NULL,
  step_id text NOT NULL,
  done_at timestamptz NOT NULL,
  PRIMARY KEY (student_id, lesson_id, step_id)
);
CREATE TABLE IF NOT EXISTS sessions (
  id text PRIMARY KEY,
  token_hash text NOT NULL UNIQUE,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL,
  last_activity_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  user_agent text NOT NULL DEFAULT '',
  remember smallint NOT NULL DEFAULT 0 CHECK (remember IN (0, 1))
);
CREATE TABLE IF NOT EXISTS login_attempts (
  normalized_login text NOT NULL,
  ip_address text NOT NULL,
  failures integer NOT NULL DEFAULT 0,
  lock_level integer NOT NULL DEFAULT 0,
  blocked_until timestamptz,
  updated_at timestamptz NOT NULL,
  PRIMARY KEY (normalized_login, ip_address)
);
CREATE TABLE IF NOT EXISTS login_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at timestamptz NOT NULL,
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  login text NOT NULL,
  success smallint NOT NULL CHECK (success IN (0, 1)),
  ip_address text NOT NULL DEFAULT '',
  user_agent text NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS audit_log (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  class_id integer REFERENCES classes(id) ON DELETE SET NULL,
  action text NOT NULL,
  target text NOT NULL DEFAULT '',
  details_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS activity_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind text NOT NULL,
  title text NOT NULL,
  details text NOT NULL DEFAULT '',
  assignment_id integer REFERENCES assignments(id) ON DELETE SET NULL,
  submission_id integer REFERENCES submissions(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL,
  read_at timestamptz
);
CREATE INDEX IF NOT EXISTS idx_classes_teacher ON classes(teacher_id, archived);
CREATE INDEX IF NOT EXISTS idx_users_class ON users(class_id, role, active);
CREATE INDEX IF NOT EXISTS idx_assignments_class_status ON assignments(class_id, status, due_at);
CREATE INDEX IF NOT EXISTS idx_submissions_status ON submissions(status, updated_at);
CREATE INDEX IF NOT EXISTS idx_submissions_student ON submissions(student_id, assignment_id);
CREATE INDEX IF NOT EXISTS idx_versions_submission ON submission_versions(submission_id, created_at);
CREATE INDEX IF NOT EXISTS idx_sessions_user_expiry ON sessions(user_id, expires_at);
CREATE INDEX IF NOT EXISTS idx_login_events_user_time ON login_events(user_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_login_attempts_expiry ON login_attempts(updated_at);
CREATE INDEX IF NOT EXISTS idx_audit_class_time ON audit_log(class_id, created_at);
CREATE INDEX IF NOT EXISTS idx_events_user_time ON activity_events(user_id, created_at);
