CREATE TABLE IF NOT EXISTS teacher_assignment_templates (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title text NOT NULL,
  config_json jsonb NOT NULL,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  UNIQUE (teacher_id, title)
);
CREATE INDEX IF NOT EXISTS idx_assignment_templates_teacher ON teacher_assignment_templates(teacher_id, title);

CREATE TABLE IF NOT EXISTS teacher_rubric_templates (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title text NOT NULL,
  criteria_json jsonb NOT NULL,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  UNIQUE (teacher_id, title)
);
CREATE INDEX IF NOT EXISTS idx_rubric_templates_teacher ON teacher_rubric_templates(teacher_id, title);

CREATE TABLE IF NOT EXISTS class_gallery_projects (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id integer NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  student_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  assignment_id integer NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
  submission_id integer NOT NULL REFERENCES submissions(id) ON DELETE CASCADE,
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  html text NOT NULL DEFAULT '',
  css text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL,
  UNIQUE (submission_id)
);
CREATE INDEX IF NOT EXISTS idx_class_gallery_class ON class_gallery_projects(class_id, created_at DESC);
